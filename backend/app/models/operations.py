import uuid

from datetime import datetime
from typing import Any

from sqlalchemy import (
    String,
    Boolean,
    Integer,
    DateTime,
    ForeignKey,
    JSON,
    UniqueConstraint,
    text,
)

from sqlalchemy.orm import Mapped, mapped_column

from app.database.base import (
    Base,
    UUIDPrimaryKeyMixin,
    TimestampMixin,
)


class RestaurantSettings(
    Base,
    UUIDPrimaryKeyMixin,
    TimestampMixin,
):

    __tablename__ = "restaurant_settings"

    settings_key: Mapped[str] = mapped_column(
        String(50),
        unique=True,
        default="default",
        nullable=False,
    )

    restaurant_name: Mapped[str] = mapped_column(
        String(150),
        nullable=False,
    )

    phone: Mapped[str | None] = mapped_column(
        String(20),
        nullable=True,
    )

    address: Mapped[str | None] = mapped_column(
        String(500),
        nullable=True,
    )

    logo_url: Mapped[str | None] = mapped_column(
        String(500),
        nullable=True,
    )

    currency: Mapped[str] = mapped_column(
        String(3),
        default="INR",
        server_default=text("'INR'"),
        nullable=False,
    )

    timezone: Mapped[str] = mapped_column(
        String(50),
        default="Asia/Kolkata",
        server_default=text("'Asia/Kolkata'"),
        nullable=False,
    )

    receipt_width_mm: Mapped[int] = mapped_column(
        Integer,
        default=80,
        server_default=text("80"),
        nullable=False,
    )


class AuditLog(Base, UUIDPrimaryKeyMixin, TimestampMixin):

    __tablename__ = "audit_logs"

    user_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )

    device_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("devices.id", ondelete="SET NULL"),
        nullable=True,
    )

    action: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
    )

    entity_type: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
    )

    entity_id: Mapped[uuid.UUID | None] = mapped_column(
        nullable=True,
    )

    old_values: Mapped[dict[str, Any] | None] = mapped_column(
        JSON,
        nullable=True,
    )

    new_values: Mapped[dict[str, Any] | None] = mapped_column(
        JSON,
        nullable=True,
    )

    details: Mapped[str | None] = mapped_column(
        String(1000),
        nullable=True,
    )


class SyncEvent(Base, UUIDPrimaryKeyMixin, TimestampMixin):

    __tablename__ = "sync_events"

    __table_args__ = (
        UniqueConstraint(
            "device_id",
            "event_id",
            name="uq_sync_device_event",
        ),
    )

    device_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("devices.id", ondelete="RESTRICT"),
        nullable=False,
    )

    # Unique identifier generated by the originating device.
    event_id: Mapped[uuid.UUID] = mapped_column(
        nullable=False,
    )

    entity_type: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
    )

    entity_id: Mapped[uuid.UUID] = mapped_column(
        nullable=False,
    )

    operation: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
    )

    payload: Mapped[dict[str, Any]] = mapped_column(
        JSON,
        nullable=False,
    )

    sync_status: Mapped[str] = mapped_column(
        String(30),
        default="pending",
        server_default=text("'pending'"),
        nullable=False,
    )

    retry_count: Mapped[int] = mapped_column(
        Integer,
        default=0,
        server_default=text("0"),
        nullable=False,
    )

    error_message: Mapped[str | None] = mapped_column(
        String(1000),
        nullable=True,
    )

    processed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )